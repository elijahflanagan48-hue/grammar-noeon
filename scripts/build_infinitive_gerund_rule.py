#!/usr/bin/env python3
"""Собирает infinitive-gerund.js и content/theory/11-infinitive-gerund-rule.html из infinitive_gerund_rule_source.py.

python3 scripts/build_infinitive_gerund_rule.py [--preview путь.html]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from infinitive_gerund_rule_source import build_html  # noqa: E402

html = build_html()
(ROOT / 'content/theory/11-infinitive-gerund-rule.html').write_text(html + '\n', encoding='utf-8')

JS = r'''"use strict";
// Published theory only; no exercise answers or grading data. Generated by scripts/build_infinitive_gerund_rule.py.
const INFINITIVE_GERUND_RULE_CONTENT = __CONTENT__;
function infinitiveGerundRuleHtml(prefix='') {
  const safePrefix=String(prefix).replace(/[^a-zA-Z0-9_-]/g,'');
  return INFINITIVE_GERUND_RULE_CONTENT
    .replace(/id="([^"]+)"/g,(_,id)=>'id="'+safePrefix+id+'" data-ig-id="'+id+'"')
    .replace(/href="#(ig-[^"]+)"/g,(_,id)=>'href="#theory/infinitive/'+id+'" data-ig-anchor="'+id+'"');
}
function revealInfinitiveGerundAnchor(container,anchor) {
  const root=container?.matches?.('.ig')?container:container?.querySelector?.('.ig');
  if(!root)return;
  const id=String(anchor||'').replace(/^#?(?:theory\/infinitive\/)?/,'');
  if(!id)return;
  const target=[root,...root.querySelectorAll('[data-ig-id]')].find(node=>node.dataset.igId===id||node.id===id);
  if(!target){const outer=document.getElementById(id);if(outer)outer.scrollIntoView({block:'start',behavior:'instant'});return;}
  for(let node=target.closest('details');node;node=node.parentElement?.closest('details'))node.open=true;
  const spot=target.closest('details')||target.closest('.ig-pair')||target.closest('.mv-sec')||target;
  const scrollArea=root.closest('.reference-reader,.rule-dialog-content');
  if(scrollArea){
    const nav=root.querySelector('.mv-nav');
    scrollArea.scrollTop+=spot.getBoundingClientRect().top-scrollArea.getBoundingClientRect().top-(nav?.getBoundingClientRect().height||0)-16;
  }else spot.scrollIntoView({block:'start',behavior:'instant'});
  if(spot.classList?.contains('ig-pair')){spot.classList.add('ig-flash');setTimeout(()=>spot.classList.remove('ig-flash'),1200);}
}
function igPick(group,selector,el){
  group.querySelectorAll(selector).forEach(b=>{const on=b===el;b.classList.toggle('on',on);b.setAttribute('aria-pressed',String(on));});
}
function igFilter(sec){
  const pill=sec.querySelector('.ig-filter [aria-pressed="true"]');
  const f=pill?pill.dataset.f:'all';
  const q=(sec.querySelector('.ig-search input')?.value||'').trim().toLowerCase();
  let shown=0;
  sec.querySelectorAll('.sv-ph').forEach(p=>{
    const hide=(f!=='all'&&p.dataset.v!==f)||(q&&!p.dataset.w.includes(q));
    p.hidden=hide;if(hide)p.open=false;else shown++;
  });
  const none=sec.querySelector('.ig-none');if(none)none.hidden=shown>0;
}
function initialiseInfinitiveGerundRule(container) {
  const root=container?.matches?.('.ig')?container:container?.querySelector?.('.ig');
  if(!root||root.dataset.initialised)return;
  root.dataset.initialised='true';
  root.addEventListener('input',event=>{
    const input=event.target.closest?.('.ig-search input');
    if(input&&root.contains(input))igFilter(input.closest('.mv-sec'));
  });
  root.addEventListener('click',event=>{
    const t=event.target;
    const link=t.closest?.('[data-ig-anchor]');
    if(link&&root.contains(link)&&event.button===0&&!event.metaKey&&!event.ctrlKey&&!event.altKey&&!event.shiftKey){
      event.preventDefault();event.stopPropagation();revealInfinitiveGerundAnchor(root,link.dataset.igAnchor);return;
    }
    const lens=t.closest?.('.sv-lens');
    if(lens&&root.contains(lens)){
      igPick(lens.parentElement,'.sv-lens',lens);
      root.querySelectorAll('.sv-lp').forEach(p=>{p.hidden=p.dataset.v!==lens.dataset.v;});
      return;
    }
    const slot=t.closest?.('.sv-slot');
    if(slot&&root.contains(slot)){
      const board=slot.closest('.sv-board');
      igPick(slot.parentElement,'.sv-slot',slot);
      board.querySelectorAll('.sv-sd').forEach(d=>{d.hidden=d.dataset.s!==slot.dataset.s;});
      return;
    }
    const pb=t.closest?.('.ig-pb');
    if(pb&&root.contains(pb)){
      const pair=pb.closest('.ig-pair');
      igPick(pb.parentElement,'.ig-pb',pb);
      pair.querySelectorAll('.ig-pp').forEach(p=>{p.hidden=p.dataset.k!==pb.dataset.k;});
      return;
    }
    const ax=t.closest?.('.ig-ax');
    if(ax&&root.contains(ax)){
      const b=ax.closest('.ig-builder');
      igPick(ax.parentElement,'.ig-ax',ax);
      const val=name=>b.querySelector('[data-axis="'+name+'"] .ig-ax.on')?.dataset.val;
      const key=val('when')+'-'+val('voice')+'-'+val('cont');
      b.querySelectorAll('.ig-fbr').forEach(r=>{r.hidden=r.dataset.key!==key;});
      return;
    }
    const pill=t.closest?.('.ig-filter button');
    if(pill&&root.contains(pill)){
      pill.parentElement.querySelectorAll('button').forEach(b=>b.setAttribute('aria-pressed',String(b===pill)));
      igFilter(pill.closest('.mv-sec'));return;
    }
    const trap=t.closest?.('.sv-trap');
    if(trap&&root.contains(trap)){
      const on=!trap.classList.contains('on');
      trap.classList.toggle('on',on);trap.setAttribute('aria-expanded',String(on));return;
    }
    const option=t.closest?.('.sv-opts button');
    if(option&&root.contains(option)){
      const q=option.closest('.sv-q');
      if(q.classList.contains('done'))return;
      const right=option.hasAttribute('data-ok');
      q.classList.add('done',right?'ok':'bad');
      q.querySelectorAll('.sv-opts button').forEach(b=>{b.disabled=true;if(b.hasAttribute('data-ok'))b.classList.add('sv-right');});
      if(!right)option.classList.add('sv-wrong');
      const gap=q.querySelector('.sv-gap');if(gap)gap.textContent=q.querySelector('[data-ok]').textContent;
      q.querySelector('.sv-why').hidden=false;
      const quiz=q.closest('.sv-quiz');
      const all=quiz.querySelectorAll('.sv-q'),done=quiz.querySelectorAll('.sv-q.done');
      if(all.length===done.length){
        let foot=quiz.querySelector('.sv-score');
        if(!foot){foot=document.createElement('div');foot.className='sv-score';quiz.append(foot);}
        foot.replaceChildren();
        const text=document.createElement('span');text.textContent='Результат: '+quiz.querySelectorAll('.sv-q.ok').length+' из '+all.length;
        const again=document.createElement('button');again.type='button';again.className='sv-again';again.textContent='Ещё раз';
        foot.append(text,again);
      }
      return;
    }
    const again=t.closest?.('.sv-again');
    if(again&&root.contains(again)){
      const quiz=again.closest('.sv-quiz');
      quiz.querySelectorAll('.sv-q').forEach(q=>{q.classList.remove('done','ok','bad');q.querySelector('.sv-why').hidden=true;const g=q.querySelector('.sv-gap');if(g)g.textContent='___';q.querySelectorAll('button').forEach(b=>{b.disabled=false;b.classList.remove('sv-right','sv-wrong');});});
      quiz.querySelector('.sv-score')?.remove();
    }
  });
}
'''
(ROOT / 'infinitive-gerund.js').write_text(JS.replace('__CONTENT__', json.dumps(html, ensure_ascii=False)), encoding='utf-8')

if '--preview' in sys.argv:
    out = Path(sys.argv[sys.argv.index('--preview') + 1])
    css = '\n'.join((ROOT / n).read_text(encoding='utf-8') for n in ('modal-verbs.css', 'speaking-verbs.css', 'infinitive-gerund.css'))
    js = (ROOT / 'infinitive-gerund.js').read_text(encoding='utf-8')
    page = '''<!DOCTYPE html>
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Infinitive · -ing — Grammar NOEON</title>
<style>
:root{--bg:#f3f6fb;--surf:#fff;--surf2:#f2f6fd;--tx:#0f1a2e;--mut:#52627d;--line:#e4eaf4;--pri:#24675b;--pri-soft:#e4efe8}
:root[data-theme="dark"]{--bg:#070c17;--surf:#0f1726;--surf2:#141e32;--tx:#e8eefb;--mut:#a2afc8;--line:#1b2538;--pri:#83d4b5;--pri-soft:#12362b}
body{margin:0;background:var(--bg);font-family:-apple-system,"Segoe UI",Roboto,system-ui,sans-serif}
main{max-width:1120px;margin:0 auto;padding:18px 14px 60px}
CSS
</style></head><body>
<main id="pv"></main>
<script>
JS
document.getElementById('pv').innerHTML=infinitiveGerundRuleHtml();
initialiseInfinitiveGerundRule(document.getElementById('pv'));
if(location.hash==='#dark')document.documentElement.dataset.theme='dark';
</script></body></html>'''.replace('CSS\n', css + '\n').replace('JS\n', js + '\n')
    out.write_text(page, encoding='utf-8')
    print('preview', out)
print('ok', len(html))
