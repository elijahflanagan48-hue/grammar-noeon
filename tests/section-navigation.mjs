import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx={module:{exports:{}},document:{querySelector(){return {}}},localStorage:{getItem(){return null}}};
vm.createContext(ctx);vm.runInContext(fs.readFileSync(new URL('../app.js',import.meta.url),'utf8'),ctx);
ctx.entries=JSON.parse(fs.readFileSync(new URL('../data/theory.json',import.meta.url)));
vm.runInContext('state.theory=entries',ctx);
const passive=ctx.theoryNav('passive','pv-focus');
assert(passive.includes('href="#grammar"'));
assert(passive.includes('Passive Voice'));
assert(passive.includes('aria-current="location">Зачем пассив'));
for(const id of ['pv-table','pv-focus','pv-modals'])assert(passive.includes('#theory/passive/'+id));
for(const id of ['foundations','present','past','future','contrasts','comparison'])assert(!passive.includes('#theory/'+id));
const tenses=ctx.theoryNav('present','present-perfect-simple');
assert(tenses.includes('Tenses'));
for(const id of ['foundations','present','past','future','contrasts'])assert(tenses.includes('#theory/'+id));
assert(!tenses.includes('#theory/passive'));
assert(!tenses.includes('#theory/comparison'));
const comparison=ctx.theoryNav('comparison','равенство-и-неравенство');
assert(comparison.includes('aria-current="location">Конструкции'));
assert(comparison.includes('#practice/comparison'));
assert(!comparison.includes('#theory/present'));
assert(!comparison.includes('#theory/passive'));
assert(ctx.theoryNav('passive','pv-reporting').includes('aria-current="location">Особые конструкции'));
console.log('Section navigation: grammar catalog path, section-only topics, practice links and deep-link breadcrumb groups passed.');
