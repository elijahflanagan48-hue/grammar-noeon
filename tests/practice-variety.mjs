import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
import {diversifyOrder,varietySkeleton,balancedPractice} from '../cloudflare/generated/selection.mjs';
let seed=123456;
const random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/2**32);
const pool=Array.from({length:200},(_,i)=>{const k=i%10;return {id:'variety-'+i,cell:'D'+k,type:k%2?'multiple_choice':'open_brackets',layout:k===0?'mini_text':'sentence',level:['basic','medium'][k%2],topic:'tenses',practice_tenses:['present_simple','past_simple'][k%2].split(),prompt:`Opening${k} subject${k} continues.`,skeleton:'skeleton'+k,blanks:[{base_verb:'verb'+k}]};});
const shuffled=pool.map(x=>({x,n:random()})).sort((a,b)=>a.n-b.n).map(({x})=>x);
const matches=items=>items.slice(1).reduce((n,x,i)=>n+Number(x.cell===items[i].cell),0);
const ordered=diversifyOrder(shuffled);
assert(matches(shuffled)>=3*matches(ordered));
assert(matches(shuffled)>0);
assert.deepEqual(ordered.map(x=>x.id).sort(),pool.map(x=>x.id).sort());
const quotas=items=>items.reduce((out,x)=>{const key=x.topic+'/'+x.level+'/'+x.cell;out[key]=(out[key]||0)+1;return out;},{});
assert.deepEqual(quotas(ordered),quotas(pool));
for(let i=1;i<ordered.length;i++)assert(!(ordered[i].layout==='mini_text'&&ordered[i-1].layout==='mini_text'));
assert.equal(balancedPractice([{...pool[0],retired:'passive-v7'}],1).length,0);
const prompts=['She (to interrupt) during the rehearsal.', 'By the time he arrived, it (to finish).','Who (to tell) you?','A parcel ___ recently.','— What did they do now?'];
const py=spawnSync('python3',['-c','import json,sys;sys.path.insert(0,"scripts");from audit_variety import skeleton;print(json.dumps([skeleton(p) for p in json.loads(sys.stdin.read())]))'],{input:JSON.stringify(prompts),encoding:'utf8'});
assert.equal(py.status,0,py.stderr);
assert.deepEqual(prompts.map(varietySkeleton),JSON.parse(py.stdout));
console.log(`Practice variety: neighbouring matches ${matches(shuffled)} → ${matches(ordered)}; IDs and quotas preserved; Python/JS skeleton parity.`);
